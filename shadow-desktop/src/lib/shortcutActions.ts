// Global shortcut action registry + dispatcher.
//
// The Rust hook (src-tauri/src/global_keys.rs) reports pressed chords
// as action ids; runShortcutAction maps an id onto app behaviour. The
// same registry drives the settings UI rows (SHORTCUT_ACTION_IDS).

import { safeInvoke } from './tauriSafe';
import { useConversationStore } from '../stores/conversationStore';

export const SHORTCUT_ACTION_IDS = [
  'window_toggle',
  'window_hide',
  'nav_tasks',
  'nav_conversation',
  'nav_settings',
  'conversation_new',
  'recording_toggle',
] as const;

export type ShortcutActionId = (typeof SHORTCUT_ACTION_IDS)[number];

/** Mirrors recording::RecordingSession in the Rust backend. */
interface RecordingSessionDto {
  id: string;
  mode: string;
  started_at: string;
  ended_at: string | null;
  wallclock_start_ms: number;
}

function newConversationId(): string {
  return typeof crypto !== 'undefined' && crypto.randomUUID
    ? crypto.randomUUID()
    : `c-${Date.now()}-${Math.random().toString(16).slice(2)}`;
}

/**
 * Execute a triggered shortcut action. Unknown ids (e.g. a stale
 * binding for an action that no longer exists) are ignored silently.
 */
export async function runShortcutAction(
  action: string,
  navigate: (to: string) => void,
): Promise<void> {
  switch (action) {
    case 'window_toggle':
      await safeInvoke('toggle_window_visibility');
      return;

    case 'window_hide':
      await safeInvoke('hide_window');
      return;

    case 'nav_tasks':
      await showAndNavigate(navigate, '/tasks');
      return;

    case 'nav_conversation':
      await showAndNavigate(navigate, '/conversation');
      return;

    case 'nav_settings':
      await showAndNavigate(navigate, '/settings');
      return;

    case 'conversation_new': {
      await safeInvoke('show_window');
      useConversationStore.getState().addConversation({
        id: newConversationId(),
        kind: 'text',
        title: '新会话',
        messages: [],
        createdAt: new Date(),
        updatedAt: new Date(),
      });
      navigate('/conversation');
      return;
    }

    case 'recording_toggle': {
      // One toggle covers the whole lifecycle: no live session → start
      // an audio recording; a live session exists → stop it (the
      // summary report is generated by the backend on stop).
      const sessions =
        (await safeInvoke<RecordingSessionDto[]>('recording_list')) ?? [];
      const live = sessions.find((s) => !s.ended_at);
      if (live) {
        await safeInvoke('recording_stop', { sessionId: live.id });
        useConversationStore
          .getState()
          .updateConversation(live.id, {
            recordingEndedAt: new Date().toISOString(),
          });
        await showAndNavigate(navigate, '/conversation');
        return;
      }
      const started = await safeInvoke<RecordingSessionDto>('recording_start', {
        mode: 'audio',
      });
      if (started) {
        useConversationStore.getState().addConversation({
          id: started.id,
          kind: 'audio',
          title: '语音会话',
          messages: [],
          createdAt: new Date(),
          updatedAt: new Date(),
          recordingStartedAt: started.started_at,
          recordingEndedAt: started.ended_at,
          recordingWallclockStartMs: started.wallclock_start_ms,
        });
      }
      await showAndNavigate(navigate, '/conversation');
      return;
    }

    default:
      return;
  }
}

async function showAndNavigate(
  navigate: (to: string) => void,
  to: string,
): Promise<void> {
  // The trigger may arrive while the window is hidden in the tray.
  await safeInvoke('show_window');
  navigate(to);
}
