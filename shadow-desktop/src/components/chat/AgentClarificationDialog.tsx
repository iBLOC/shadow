import { useState, useEffect, useMemo } from 'react';
import { useTranslation } from 'react-i18next';
import {
  Questionnaire,
  QuestionnaireActions,
  QuestionnaireChoice,
  QuestionnaireChoiceDescription,
  QuestionnaireChoices,
  QuestionnaireDescription,
  QuestionnaireInput,
  QuestionnaireItem,
  QuestionnaireNext,
  QuestionnairePrevious,
  QuestionnaireProgress,
  QuestionnaireSkip,
  QuestionnaireSubmit,
  QuestionnaireTitle,
} from '@/components/ui/questionnaire';
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog';
import { Brain } from 'lucide-react';

/**
 * One question the agent asks the user. Mirrors the @shadcn/helpers
 * `askQuestions` example: a question has a fixed set of choices and
 * an optional freeform "another answer" input.
 */
export interface ClarificationChoice {
  value: string;
  label: string;
  description?: string;
  /** Letter/number shortcut for the choice. */
  shortcut?: string;
}

export interface ClarificationItem {
  name: string;
  prompt: string;
  description?: string;
  required?: boolean;
  choices: ClarificationChoice[];
  /** Optional freeform input (shown after the fixed choices). */
  freeform?: {
    label: string;
    placeholder?: string;
  };
  /** Skip-this-question button — only for non-required items. */
  skippable?: boolean;
}

export interface AgentClarificationDialogProps {
  open: boolean;
  /** Title shown in the dialog header. */
  title?: string;
  /** Optional list of clarification items to ask. When empty the
   *  dialog shows an empty state and cannot be submitted. */
  items: ClarificationItem[];
  /** Called with the final answers map when the user submits. */
  onSubmit: (answers: Record<string, string | string[]>) => void;
  /** Called when the user dismisses the dialog without submitting. */
  onCancel?: () => void;
  /** Render a compact layout (saves vertical space). */
  compact?: boolean;
}

/**
 * Render a multi-step clarification prompt generated by the agent.
 *
 * This is the front-end surface for the `askQuestions` tool defined
 * in `src/lib/chat/ClientToolForm.tsx`. When the agent's prompt
 * includes such a tool, the streaming response surfaces it as a
 * tool part with `state === "input-available"`; this dialog
 * renders that part using the shadcn/ui Questionnaire primitive.
 *
 * Answer collection:
 * - Single choice items store the chosen `value` (string).
 * - Multi-choice items store an array of chosen values.
 * - Freeform input appends to the choice under the
 *   `__freeform:<name>` field so the consumer can distinguish.
 */
export function AgentClarificationDialog({
  open,
  title,
  items,
  onSubmit,
  onCancel,
  compact = false,
}: AgentClarificationDialogProps) {
  const { t } = useTranslation();
  const [answers, setAnswers] = useState<Record<string, string | string[]>>({});
  const [freeform, setFreeform] = useState<Record<string, string>>({});

  // Reset transient state whenever the dialog re-opens with new items.
  useEffect(() => {
    if (open) {
      setAnswers({});
      setFreeform({});
    }
  }, [open, items]);

  const itemCount = items.length;
  const effectiveTitle = title ?? t('questionnaire.agentClarify.title');

  const wrappedItems = useMemo(
    () =>
      items.map((item) => ({
        ...item,
        freeform: item.freeform ?? {
          label: 'Another answer',
          placeholder: 'Type another answer…',
        },
        skippable: item.skippable ?? !item.required,
      })),
    [items],
  );

  function handleSubmit(event: React.FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const form = event.currentTarget;
    const merged: Record<string, string | string[]> = { ...answers };

    // Walk every item; pull its current value(s) from the native form
    // (Questionnaire renders native radio/checkbox inputs).
    for (const item of items) {
      const nodeList = form.elements.namedItem(item.name);
      if (!nodeList) continue;
      if (nodeList instanceof RadioNodeList) {
        merged[item.name] = nodeList.value;
      } else {
        // CheckboxNodeList — collect all checked values.
        const list = nodeList as unknown as { length: number; [i: number]: HTMLInputElement };
        if (typeof list.length === 'number') {
          const values: string[] = [];
          for (let i = 0; i < list.length; i++) {
            if (list[i].checked) values.push(list[i].value);
          }
          if (values.length > 0) merged[item.name] = values;
        }
      }
    }

    for (const [k, v] of Object.entries(freeform)) {
      if (v.trim()) merged[k] = v.trim();
    }
    onSubmit(merged);
  }

  if (itemCount === 0) {
    return (
      <Dialog open={open} onOpenChange={(v) => !v && onCancel?.()}>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>{effectiveTitle}</DialogTitle>
          </DialogHeader>
          <p className="text-sm text-muted-foreground">
            {t('questionnaire.agentClarify.description')}
          </p>
        </DialogContent>
      </Dialog>
    );
  }

  return (
    <Dialog open={open} onOpenChange={(v) => !v && onCancel?.()}>
      <DialogContent
        className={compact ? 'max-w-lg' : 'max-w-2xl'}
        data-testid="agent-clarification-dialog"
      >
        <DialogHeader>
          <div className="flex items-center gap-2">
            <Brain className="h-5 w-5 text-primary" />
            <DialogTitle>{effectiveTitle}</DialogTitle>
          </div>
          <p className="text-sm text-muted-foreground">
            {t('questionnaire.agentClarify.description')}
          </p>
        </DialogHeader>

        <Questionnaire
          items={wrappedItems as never}
          onSubmit={handleSubmit}
          className={compact ? 'gap-2' : 'gap-4'}
        >
          <QuestionnaireProgress />

          {wrappedItems.map((item) => (
            <QuestionnaireItem
              key={item.name}
              name={item.name}
              required={item.required ?? false}
            >
              <QuestionnaireTitle>{item.prompt}</QuestionnaireTitle>
              {item.description && (
                <QuestionnaireDescription>
                  {item.description}
                </QuestionnaireDescription>
              )}

              <QuestionnaireChoices
              >
                {item.choices.map((choice) => (
                  <QuestionnaireChoice
                    key={choice.value}
                    value={choice.value}
                    {...(choice.shortcut ? { shortcut: choice.shortcut } : {})}
                  >
                    <span className="font-medium">{choice.label}</span>
                    {choice.description && (
                      <QuestionnaireChoiceDescription>
                        {choice.description}
                      </QuestionnaireChoiceDescription>
                    )}
                  </QuestionnaireChoice>
                ))}

                <QuestionnaireInput
                  aria-label={item.freeform.label}
                  placeholder={item.freeform.placeholder}
                  value={freeform[item.name] ?? ''}
                  onChange={(e) =>
                    setFreeform((prev) => ({
                      ...prev,
                      [item.name]: e.target.value,
                    }))
                  }
                />
              </QuestionnaireChoices>
            </QuestionnaireItem>
          ))}

          <QuestionnaireActions>
            <QuestionnairePrevious>
              {t('questionnaire.agentClarify.previous')}
            </QuestionnairePrevious>
            <QuestionnaireSkip>
              {t('questionnaire.agentClarify.skip')}
            </QuestionnaireSkip>
            <QuestionnaireNext>
              {t('questionnaire.agentClarify.previous')}
            </QuestionnaireNext>
            <QuestionnaireSubmit>
              {t('questionnaire.agentClarify.submit')}
            </QuestionnaireSubmit>
          </QuestionnaireActions>
        </Questionnaire>
      </DialogContent>
    </Dialog>
  );
}
